"""Measuring appendices that follow the reference list.

Many papers print their appendices after the bibliography. The audit measured
each page section against its span in the source, and three things went wrong
on such a paper, each producing findings about sections that were complete:

* the key read `C.2` as the roman numeral `C`, so every subsection of
  appendix C was reported as a copy of the others;
* the source was cut at the last `References`, which removed the appendices,
  so an appendix subsection was found only in the table of contents at the top
  and measured against the body text that follows it there;
* the last section ran to the end of the arXiv page, so the page's own chrome
  was counted as that section's source text;
* measured to the end of the document, the last appendix also took in the
  unlettered back matter after it, a NeurIPS paper checklist.
"""
import json
import sys

import pytest

import verify_sections as vs

SENTENCE = ("The method is evaluated on a range of tasks and compared with the "
            "baselines described above. ")


def prose(chars):
    """Paragraph lines of ordinary prose, about `chars` characters in all."""
    lines, made = [], 0
    while made < chars:
        line = SENTENCE * 4
        lines.append(line.strip())
        made += len(line)
    return "\n".join(lines)


BIBLIOGRAPHY = "\n".join(
    f"[{n}] A. Author and B. Author. A title of a cited work, number {n}. "
    f"In Proceedings of a Conference, pages 1-10, 2020." for n in range(1, 16))

CHROME = ("Experimental support, please view the build logs for errors. "
          "Generated by L A T E xml . Instructions for reporting errors. "
          "We are continuing to improve HTML versions of papers, and your feedback "
          "helps enhance accessibility and mobile support. To report errors in the "
          "HTML that will help us improve conversion and rendering, choose any of "
          "the methods listed below. Click the Report Issue button. Open a report "
          "feedback form via keyboard, use Ctrl and the question mark key. Make a "
          "text selection and click the Report Issue for Selection button near "
          "your cursor. You can use Alt and Y to toggle accessibility mode on and "
          "off, which highlights the elements of the page that can be reported.")

TOC = "\n".join(["1 Introduction", "2 Method", "References",
                 "A Additional Experiments", "A.1 Setup Details",
                 "A.2 Ablation Results"])

SPANS = {"1": prose(3000), "2": prose(3000), "A": prose(600),
         "A.1": prose(1200), "A.2": prose(900)}


def source(chrome=CHROME):
    return "\n".join([
        TOC,
        "1 Introduction", SPANS["1"],
        "2 Method", SPANS["2"],
        "References", BIBLIOGRAPHY,
        "A Additional Experiments", SPANS["A"],
        "A.1 Setup Details", SPANS["A.1"],
        "A.2 Ablation Results", SPANS["A.2"],
        chrome,
    ])


SECTIONS = [("1", "Introduction"), ("2", "Method"),
            ("A", "Additional Experiments"), ("A.1", "Setup Details"),
            ("A.2", "Ablation Results")]


def measured(text=None):
    return vs.source_section_chars(text or source(), SECTIONS)


def complete_translation(ratio=0.6):
    """Translated length per section of a page that translated everything."""
    return {key: int(len(SPANS[key]) * ratio) for key, _ in SECTIONS}


def audit(monkeypatch, capsys, text, sizes, extra=()):
    """Findings of the full audit on a page with `sizes[key]` chars per section."""
    def block(kind, content, bid):
        return {"type": kind, "id": bid, "has_children": False,
                kind: {"rich_text": [{"type": "text", "plain_text": content,
                                      "text": {"content": content}}]}}
    korean = "번역된 본문 문장이 이어집니다. "
    page = []
    for key, title in SECTIONS:
        page += [block("heading_2", f"{key} {title} (번역 제목)", f"h{key}"),
                 block("paragraph", (korean * 400)[:sizes[key]], f"p{key}")]
    page += list(extra)
    monkeypatch.setattr(vs, "fetch_blocks", lambda _: page)
    monkeypatch.setattr(vs, "page_title", lambda _: "a paper")
    monkeypatch.setattr(vs, "load_source_text", lambda *_: text)
    monkeypatch.setattr(sys, "argv", ["verify_sections.py", "--page", "p",
                                      "--arxiv", "test-paper", "--json"])
    vs.main()
    return json.loads(capsys.readouterr().out)["findings"]


def close_to(got, key, slack=80):
    """The span measured for `key` is its own text, give or take a heading line."""
    want = len(SPANS[key])
    return got is not None and abs(got - want) <= slack


class TestAppendixSubsectionKeys:

    def test_a_dotted_appendix_subsection_keeps_its_number(self):
        assert vs.section_key("C.2 Ablation Results (절제 결과)") == "C.2"

    def test_every_letter_a_roman_numeral_shadowed(self):
        for letter in "CILVX":
            assert vs.section_key(f"{letter}.3 Details (세부 사항)") == f"{letter}.3"

    def test_roman_and_appendix_labels_are_unchanged(self):
        assert vs.section_key("III-A Setup (설정)") == "III-A"
        assert vs.section_key("IV Experiments (실험)") == "IV"
        assert vs.section_key("C. Proofs (증명)") == "C"
        assert vs.section_key("2.1 Data (데이터)") == "2.1"

    def test_appendix_subsections_are_not_copies_of_each_other(self):
        def block(kind, text, bid):
            return {"type": kind, "id": bid,
                    kind: {"rich_text": [{"type": "text", "plain_text": text,
                                          "text": {"content": text}}]}}
        blocks = [block("heading_1", "C Further Results (추가 결과)", "h0"),
                  block("paragraph", "부록 C의 도입 문단입니다. " * 6, "p0")]
        for n, (title, body) in enumerate([
                ("Setup (설정)", "설정은 다음과 같습니다. "),
                ("Ablation (절제)", "절제 실험의 결과입니다. "),
                ("Compute (연산)", "연산 자원은 이렇습니다. ")], start=1):
            blocks += [block("heading_2", f"C.{n} {title}", f"h{n}"),
                       block("paragraph", body * 6, f"p{n}")]
        groups = vs.duplicate_groups(vs.group_sections(blocks))
        assert [occ for occ in groups.values() if len(occ) > 1] == []


class TestAppendicesAfterTheReferences:

    def test_an_appendix_subsection_is_measured_where_it_is(self):
        # Not in the table of contents at the top, against the body after it.
        assert close_to(measured()["A.1"], "A.1")

    def test_the_bibliography_is_not_counted_into_the_section_before_it(self):
        assert close_to(measured()["2"], "2")

    def test_the_body_sections_are_measured_as_before(self):
        assert close_to(measured()["1"], "1")

    def test_an_appendix_subsection_the_page_lacks_is_not_counted_into_its_parent(self):
        # The page carries A and A.2 but not A.1: A's span must stop at the
        # A.1 heading the source shows, as it would at a numbered one.
        sections = [s for s in SECTIONS if s[0] != "A.1"]
        assert close_to(vs.source_section_chars(source(), sections)["A"], "A")

    def test_an_appendix_the_page_lacks_is_not_counted_into_the_one_before(self):
        extra = "\n".join(["Appendix B Further Results", prose(2000),
                           "B.1 More Ablations", prose(1500)])
        text = source(chrome=extra + "\n" + CHROME)
        assert close_to(vs.source_section_chars(text, SECTIONS)["A.2"], "A.2")

    def test_a_sentence_opening_with_a_capital_letter_is_not_a_heading(self):
        text = source().replace(SPANS["A.1"], "A New Setup Was Used\n" + SPANS["A.1"])
        assert vs.source_section_chars(text, SECTIONS)["A.1"] > len(SPANS["A.1"])

    def test_a_paper_without_appendices_is_still_cut_at_its_references(self):
        text = "\n".join([TOC, "1 Introduction", SPANS["1"], "2 Method",
                          SPANS["2"], "References", BIBLIOGRAPHY, CHROME])
        got = vs.source_section_chars(text, SECTIONS[:2])
        assert close_to(got["2"], "2")


EXAMPLE_CELL = ("Question: does the worked example in this cell read like a sentence? "
                "Answer: it does, which is why a short-line rule cannot see it.")


def table(tid, rows=6, inner=""):
    cells = "".join(f"<tr><td>Example {n}</td><td>{EXAMPLE_CELL}</td></tr>"
                    for n in range(rows))
    return (f'<figure id="{tid}" class="ltx_table"><table class="ltx_tabular">'
            f"{cells}</table>{inner}<figcaption>Table {tid}: Worked examples."
            f"</figcaption></figure>")


def html_source(tables="", tail_table="", a1=None):
    para = lambda text: "".join(f"<p>{line}</p>" for line in text.splitlines())
    return "".join([
        '<nav class="ltx_TOC">' + "".join(f"<li>{t}</li>" for t in TOC.splitlines()) + "</nav>",
        "<h2>1 Introduction</h2>", para(SPANS["1"]),
        "<h2>2 Method</h2>", para(SPANS["2"]),
        "<h2>References</h2><ul>",
        "".join(f"<li>{line}</li>" for line in BIBLIOGRAPHY.splitlines()), "</ul>",
        "<h2>A Additional Experiments</h2>", para(SPANS["A"]),
        "<h3>A.1 Setup Details</h3>", para(SPANS["A.1"] if a1 is None else a1), tables,
        "<h3>A.2 Ablation Results</h3>", para(SPANS["A.2"]), tail_table,
        f"<div>{CHROME}</div>",
    ])


ONE_SENTENCE = "The datasets and their splits are listed in the table below."


class TestTablesAreNotSource:
    """A table is placed on the page as an image and never translated, so its
    cells are no section's text, even when every cell is a sentence."""

    def measure(self, html):
        return vs.source_section_chars(vs.source_text_from_html(html), SECTIONS)

    def test_a_table_of_sentences_is_not_counted(self):
        got = self.measure(html_source(tables=table("A1.T1") + table("A1.T2")))
        assert close_to(got["A.1"], "A.1")

    def test_a_table_inside_a_table_goes_with_it(self):
        html = html_source(tables=table("A1.T1", inner=table("A1.T1.sub")))
        text = vs.source_text_from_html(html)
        assert EXAMPLE_CELL not in text and "Worked examples" not in text
        assert close_to(self.measure(html)["A.1"], "A.1")

    def test_the_prose_around_a_table_is_kept(self):
        text = vs.source_text_from_html(html_source(tables=table("A1.T1")))
        assert SPANS["A.1"].splitlines()[0] in text
        assert "Worked examples" not in text

    def test_a_sentence_and_a_table_is_a_small_section_not_a_lost_one(self):
        # Unmeasured, a section is held to the empty-section rule instead, and
        # its one translated sentence read as a dropped translation.
        got = self.measure(html_source(tables=table("A1.T1", rows=12), a1=ONE_SENTENCE))
        assert got["A.1"] is not None and got["A.1"] < len(ONE_SENTENCE) + 40

    def test_the_audit_does_not_call_it_a_dropped_translation(self, monkeypatch, capsys):
        sizes = complete_translation()
        sizes["A.1"] = 40
        html = html_source(tables=table("A1.T1", rows=12), a1=ONE_SENTENCE)
        findings = audit(monkeypatch, capsys, vs.source_text_from_html(html), sizes,
                         extra=[{"type": "image", "id": "img", "image": {}}])
        assert [f for f in findings if f.get("section") == "A.1"] == []

    def test_a_table_with_no_closing_tag_is_kept(self):
        # Dropping to the end of the document would take every section after it.
        broken = table("A1.T1").replace("</figure>", "")
        text = vs.source_text_from_html(html_source(tables=broken))
        assert EXAMPLE_CELL in text and SPANS["A.2"].splitlines()[0] in text


class TestThePageChromeIsNotSource:

    def test_the_last_appendix_section_ends_before_the_chrome(self):
        assert close_to(measured()["A.2"], "A.2")

    def test_the_chrome_changes_nothing_it_follows(self):
        assert measured()["A.2"] == measured(source(chrome=""))["A.2"]


# How LaTeXML's text of a NeurIPS paper checklist reads: an unnumbered heading,
# then each item's number on a line of its own, so no item opens a numbered
# heading line that would stop a span.
CHECKLIST_ITEM = ("Question: Do the claims made in the abstract and introduction "
                  "accurately reflect the contributions and scope of the work?\n"
                  "Answer: [Yes]\nJustification: " + SENTENCE * 3 + "\nGuidelines:\n"
                  "•\nThe answer NA means that the work makes no such claim. "
                  + SENTENCE * 2)


def checklist(heading="NeurIPS Paper Checklist"):
    items = ["Claims", "Limitations", "Theory Assumptions and Proofs",
             "Experimental Result Reproducibility", "Open access to data and code"]
    return "\n".join([heading] + [f"{n}.\n{item}\n{CHECKLIST_ITEM}"
                                  for n, item in enumerate(items, start=1)])


class TestBackMatterAfterTheLastAppendix:
    """Unlettered back matter after the appendices is no appendix's text."""

    @pytest.mark.parametrize("body_chars", [3000, 9000])
    def test_the_last_appendix_ends_at_the_checklist(self, monkeypatch, body_chars):
        # At 9000 the last References sits past half the document, so the tail
        # is cut there and brought back because the appendices follow it; at
        # 3000 it is not cut at all. The checklist must end the span either way.
        monkeypatch.setitem(SPANS, "1", prose(body_chars))
        monkeypatch.setitem(SPANS, "2", prose(body_chars))
        text = source(chrome=checklist() + "\n" + CHROME)
        assert close_to(measured(text)["A.2"], "A.2")

    @pytest.mark.parametrize("heading", ["NeurIPS Paper Checklist",
                                         "NeurIPS 2024 Paper Checklist",
                                         "Paper Checklist", "Checklist"])
    def test_each_form_of_the_heading_ends_it(self, heading):
        text = source(chrome=checklist(heading) + "\n" + CHROME)
        assert close_to(measured(text)["A.2"], "A.2")

    def test_a_paragraph_opening_with_the_word_is_not_a_checklist(self):
        lines = SPANS["A.2"].splitlines()
        a2 = "\n".join(lines[:1] + ["Checklist items were rated by two annotators "
                                     "and disagreements were settled by discussion."]
                        + lines[1:])
        text = source().replace(SPANS["A.2"], a2)
        assert measured(text)["A.2"] > len(SPANS["A.2"])

    def test_appendices_after_a_checklist_are_still_measured(self):
        # Some papers print the checklist between the references and the
        # appendices; it must stop a span, not end the document.
        text = source().replace("\nA Additional Experiments",
                                "\n" + checklist() + "\nA Additional Experiments")
        got = measured(text)
        assert all(close_to(got[key], key) for key in ("2", "A", "A.1", "A.2")), got

    def test_a_complete_last_appendix_is_not_reported(self, monkeypatch, capsys):
        text = source(chrome=checklist() + "\n" + CHROME)
        findings = audit(monkeypatch, capsys, text, complete_translation())
        assert [f for f in findings if f.get("section") == "A.2"] == []

    def test_a_short_last_appendix_is_not_a_dropped_translation(self, monkeypatch, capsys):
        monkeypatch.setitem(SPANS, "A.2", prose(300))
        text = source(chrome=checklist() + "\n" + CHROME)
        findings = audit(monkeypatch, capsys, text, complete_translation())
        assert [f for f in findings if f.get("section") == "A.2"] == []
